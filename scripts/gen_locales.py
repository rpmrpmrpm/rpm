#!/usr/bin/env python3
"""
Locale table generator. Single source of truth = scripts/strings.json
(key -> {en, fr, es, de, zh-Hans, [comment]}).

Emits, from the one table:

  * one Resources.resw per locale under RPM.Desktop/Strings/<locale>/ --- read by
    the desktop and by the Uno phone app, which link the same table;
  * one Localizable.strings per locale under
    RPM.iOS/Modules/RPMKit/Sources/RPMKit/Strings/<locale>.lproj/ --- read by the
    Swift phone app through RPMKit's `Loc`;
  * one strings.xml per locale under RPM.Android/core/src/main/res/values*/ ---
    read by the Android TV app and the Android phone app through `:core`'s `R.string`.

    python3 scripts/gen_locales.py

Why generate instead of editing by hand: translations live in one JSON file that can be reviewed,
keys cannot differ between locales or between apps, and a missing translation is a loud KeyError
instead of a silent fallback to English. NEVER edit any output by hand: all outputs are
overwritten on the next run, and a key that is not in strings.json is dropped.
"""

from __future__ import annotations

import json
import workspace
import sys
import os
import pathlib
import re
from xml.sax.saxutils import escape

LOCALES = ["en", "fr", "es", "de", "zh-Hans"]

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = workspace.path("scripts", "strings.json")
OUT_DIR = workspace.path("RPM.Desktop", "Strings")
SWIFT_DIR = workspace.path("RPM.iOS", "Modules", "RPMKit", "Sources", "RPMKit", "Strings")

# The .strings format is similar to C strings: only the quote and the backslash must be escaped,
# and a newline must be written as \n, not embedded.
SWIFT_HEADER = """/* AUTO-GENERATED by scripts/gen_locales.py from scripts/strings.json.
   DO NOT hand-edit: this file is overwritten on the next run, and any key not
   present in strings.json is silently dropped. Add or change strings in
   scripts/strings.json, then run gen_locales.py. */
"""


PLACEHOLDER = re.compile(r"\{(\d+)\}")


def as_swift_format(value: str) -> str:
    """`{0}` is the placeholder that .NET reads and `%1$@` is the one that Foundation reads.

    The conversion is done here, not in strings.json, so the table keeps one notation and each
    app gets the notation it can read. The placeholders are positional because the languages
    put the parts of a sentence in a different order.
    """
    return PLACEHOLDER.sub(lambda m: f"%{int(m.group(1)) + 1}$@", value)


def as_strings_literal(value: str) -> str:
    out = value.replace("\\", "\\\\").replace('"', '\\"')
    return out.replace("\n", "\\n").replace("\r", "\\r")


def write_swift(strings: dict) -> None:
    """One Localizable.strings per locale, in the .lproj layout SwiftPM expects."""
    for loc in LOCALES:
        out_dir = os.path.join(SWIFT_DIR, f"{loc}.lproj")
        os.makedirs(out_dir, exist_ok=True)

        rows = []
        for key, vals in strings.items():
            comment = vals.get("comment")
            if comment:
                rows.append(f"\n/* {comment} */\n")
            rows.append(f'"{as_strings_literal(key)}" = '
                        f'"{as_strings_literal(as_swift_format(vals[loc]))}";\n')

        with open(os.path.join(out_dir, "Localizable.strings"), "w", encoding="utf-8") as fh:
            fh.write(SWIFT_HEADER)
            fh.writelines(rows)

ANDROID_RES = workspace.path("RPM.Android", "core", "src", "main", "res")

# The Android resource folder of each locale. English is the default table, used by a device set to
# any other language. zh-Hans is a script subtag, which only the b+ form can name.
ANDROID_FOLDERS = {
    "en": "values",
    "fr": "values-fr",
    "es": "values-es",
    "de": "values-de",
    "zh-Hans": "values-b+zh+Hans",
}

ANDROID_HEADER = """<?xml version="1.0" encoding="utf-8"?>
<!-- AUTO-GENERATED by scripts/gen_locales.py from scripts/strings.json.
     DO NOT hand-edit: this file is overwritten on the next run, and any key not
     present in strings.json is silently dropped. Add or change strings in
     scripts/strings.json, then run gen_locales.py. -->
<resources>
"""


def as_android_value(value: str) -> tuple[str, bool]:
    """A strings.json value as Android resource text, and whether it contains only a literal `%`.

    `{0}` becomes `%1$s`, positional for the same reason as in the Swift table. In a string with
    placeholders, a literal `%` is doubled first, because `getString(id, args)` formats the whole
    string. A string with a `%` and no placeholders is returned with True, and is written with
    formatted="false" so that aapt and lint read it as plain text.

    aapt trims the ends of a value and merges runs of spaces, so a value with leading, trailing or
    double spaces is wrapped in double quotes, which keeps it as written. Backslash, both quote
    marks, newline, tab and a leading `@` or `?` are escaped as aapt expects, then the XML
    characters.
    """
    has_placeholders = PLACEHOLDER.search(value) is not None
    out = value
    if has_placeholders:
        out = out.replace("%", "%%")
        out = PLACEHOLDER.sub(lambda m: f"%{int(m.group(1)) + 1}$s", out)

    out = out.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"')
    out = out.replace("\n", "\\n").replace("\t", "\\t")
    if out[:1] in ("@", "?"):
        out = "\\" + out
    out = escape(out)

    if out != out.strip() or "  " in out:
        out = f'"{out}"'

    return out, (not has_placeholders and "%" in value)


def write_android(strings: dict) -> None:
    """One strings.xml per locale, in the folders named by ANDROID_FOLDERS."""
    for loc in LOCALES:
        out_dir = os.path.join(ANDROID_RES, ANDROID_FOLDERS[loc])
        os.makedirs(out_dir, exist_ok=True)

        rows = []
        for key, vals in strings.items():
            comment = vals.get("comment")
            if comment:
                # An XML comment may not contain "--".
                rows.append(f"\n    <!-- {comment.replace('--', '- -')} -->\n")
            text, literal_percent = as_android_value(vals[loc])
            plain = ' formatted="false"' if literal_percent else ""
            rows.append(f'    <string name="{key}"{plain}>{text}</string>\n')

        with open(os.path.join(out_dir, "strings.xml"), "w", encoding="utf-8") as fh:
            fh.write(ANDROID_HEADER)
            fh.writelines(rows)
            fh.write("</resources>\n")


