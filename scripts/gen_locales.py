# The phone and the Apple TV app read the same table (RPMKit's Localizable.strings). The TV app
# links RPMKit from RPM.iOS/Modules, so its keys are checked here too.
SWIFT_SOURCES = [workspace.path("RPM.iOS"), workspace.path("RPM.tvOS")]
USES = re.compile(r'Loc\.get\(\s*"([A-Za-z0-9_]+)"')


def check_swift_keys(strings: dict) -> int:
    """Checks that every `Loc.get("Key")` in the Swift apps names a key that is in the table.

    A key that is not in the table is shown on the screen as its own name, for example
    `Rpm_Stage_PinOn` where a label should be. That error is visible to the user of the app,
    not to the developer who made the mistake. This check finds it before the app runs.
    """
    missing = []

    paths = [path for root in SWIFT_SOURCES for path in pathlib.Path(root).rglob("*.swift")]
    for path in sorted(paths):
        # Tests are skipped: they use a key that is not in the table on purpose, to prove that a
        # missing key is shown as its own name.
        # The path parts are compared, not a substring: on Windows the separator is a backslash,
        # so a check for "/Tests/" would never match there.
        if ".build" in path.parts or "Tests" in path.parts:
            continue
        for n, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            for key in USES.findall(line):
                if key not in strings:
                    missing.append(f"{os.path.relpath(path, ROOT)}:{n}  {key}")

    for row in missing:
        print(f"  MISSING  {row}")

    return len(missing)


ANDROID_SOURCES = workspace.path("RPM.Android")
ANDROID_USES = re.compile(r"(?:\bR\.string\.|@string/)([A-Za-z0-9_]+)")


def check_android_keys(strings: dict) -> int:
    """Checks that every `R.string.Key` in the Android Kotlin code and every `@string/Key` in its XML
    names a key that is in the table.

    The Android build also fails on a missing key, but only after Gradle has started, and the error
    names a generated R field, not the line that uses it. This check names the line.
    """
    root = pathlib.Path(ANDROID_SOURCES)
    if not root.is_dir():
        return 0

    missing = []
    for path in sorted(root.rglob("*")):
        if path.suffix not in (".kt", ".xml") or "build" in path.parts or ".gradle" in path.parts:
            continue
        # The generated tables are the reference that the uses are checked against.
        if path.name == "strings.xml" and path.parent.name.startswith("values"):
            continue
        for n, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            for key in ANDROID_USES.findall(line):
                if key not in strings:
                    missing.append(f"{os.path.relpath(path, ROOT)}:{n}  {key}")

    for row in missing:
        print(f"  MISSING  {row}")

    return len(missing)


def check_catalogue_name(strings: dict) -> int:
    """Refuses a display string that names MusicBrainz.

    rpm names SonoVault. The catalogue data reaches the app under the SonoVault licence, so the
    app credits SonoVault, and a string that names another source is a statement about a licence,
    not a choice of words.

    This check is here as well as in the analyzer, and this one is the more important: the analyzer
    reads C#, but the phone app is Swift. This table is the one place where all apps share their
    user interface text, so one check covers all of them. Every locale is read, not only English,
    because a translator who works from "Identified on {0}" cannot know the rule.
    """
    named = []

    for key, values in strings.items():
        for loc in LOCALES:
            if "musicbrainz" in values.get(loc, "").lower():
                named.append(f"{key} [{loc}]: {values[loc]}")

    for row in named:
        print(f"  names MusicBrainz: {row}", file=sys.stderr)

    return len(named)


def main() -> None:
    with open(DATA, encoding="utf-8") as fh:
        strings = json.load(fh)

    for loc in LOCALES:
        rows = []
        for key, vals in strings.items():
            if loc not in vals:
                raise KeyError(f"'{key}' missing '{loc}' translation in strings.json")
            comment = vals.get("comment")
            row = f'  <data name="{escape(key)}" xml:space="preserve">\n'
            row += f"    <value>{escape(vals[loc])}</value>\n"
            if comment:
                row += f"    <comment>{escape(comment)}</comment>\n"
            row += "  </data>\n"
            rows.append(row)
        out_dir = os.path.join(OUT_DIR, loc)
        os.makedirs(out_dir, exist_ok=True)
        with open(os.path.join(out_dir, "Resources.resw"), "w", encoding="utf-8") as fh:
            fh.write(HEADER)
            fh.writelines(rows)
            fh.write("</root>\n")
        print(f"  {loc}: {len(rows)} keys")

    write_swift(strings)
    write_android(strings)
    print(f"Wrote {len(LOCALES)} locales from {len(strings)} keys, for all three heads.")

    missing = check_swift_keys(strings)
    if missing:
        raise SystemExit(f"{missing} key(s) used by the Swift head are not in strings.json")

    missing = check_android_keys(strings)
    if missing:
        raise SystemExit(f"{missing} key(s) used by the Android apps are not in strings.json")

    named = check_catalogue_name(strings)
    if named:
        raise SystemExit(
            f"{named} display string(s) name MusicBrainz. rpm names SonoVault; see RPM003")


if __name__ == "__main__":
    main()
