#!/usr/bin/env python3
"""
The Mac bundle's permission sentences, from scripts/strings.json.

macOS shows NSMicrophoneUsageDescription and NSLocalNetworkUsageDescription under
its own question ("'rpm' would like to access the microphone."). The question is in
the system's language; the sentence is the app's. macOS reads it from
<lang>.lproj/InfoPlist.strings in the bundle's Resources when the bundle has one for
the user's language, and from Info.plist otherwise.

    python3 scripts/infoplist_strings.py en <key>
        prints the English sentence for one Info.plist key, for Info.plist itself;
    python3 scripts/infoplist_strings.py write <Contents/Resources>
        writes <lang>.lproj/InfoPlist.strings for every locale.

release-mac.sh runs both before codesign, because the bundle's resources are sealed
into the signature.
"""

from __future__ import annotations

import json
import workspace
import os
import sys

LOCALES = ["en", "fr", "es", "de", "zh-Hans"]

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = workspace.path("scripts", "strings.json")

# Info.plist key -> strings.json key.
SENTENCES = {
    "NSMicrophoneUsageDescription": "Mac_MicrophoneUsage",
    "NSLocalNetworkUsageDescription": "Mac_LocalNetworkUsage",
}


def table() -> dict:
    with open(DATA, encoding="utf-8-sig") as f:
        return json.load(f)


def quoted(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def write(resources: str) -> None:
    strings = table()
    for locale in LOCALES:
        folder = os.path.join(resources, f"{locale}.lproj")
        os.makedirs(folder, exist_ok=True)
        lines = [f"{quoted(plist_key)} = {quoted(strings[key][locale])};"
                 for plist_key, key in SENTENCES.items()]
        with open(os.path.join(folder, "InfoPlist.strings"), "w", encoding="utf-8") as f:
            f.write("/* Generated by scripts/infoplist_strings.py from scripts/strings.json. */\n")
            f.write("\n".join(lines) + "\n")


def main(argv: list[str]) -> int:
    if len(argv) == 3 and argv[1] == "en" and argv[2] in SENTENCES:
        print(table()[SENTENCES[argv[2]]]["en"])
        return 0
    if len(argv) == 3 and argv[1] == "write":
        write(argv[2])
        return 0
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
