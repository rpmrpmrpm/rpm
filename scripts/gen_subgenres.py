#!/usr/bin/env python3
"""Writes RPM.Core/Metadata/Subgenres.Data.cs, the iPhone's Subgenres.Data.swift and the Android
TV app's SubgenreTable.kt from scripts/subgenres.json.

One source, three generated tables, in the same way as gen_locales.py for display strings. All three
files are overwritten on every run and are never edited by hand: a shelf or a style removed from the
JSON disappears from every app, and one that is added appears in all of them at once.

Run after editing scripts/subgenres.json:

    python3 scripts/gen_subgenres.py
"""

import hashlib
import json
import workspace
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = workspace.path("scripts", "subgenres.json")
TARGET = workspace.path("RPM.Core", "Metadata", "Subgenres.Data.cs")
SWIFT_TARGET = workspace.path("RPM.iOS", "Modules", "RPMLibrary", "Sources", "RPMLibrary",
                            "Subgenres.Data.swift")
KOTLIN_TARGET = workspace.path("RPM.Android", "core", "src", "main", "java", "com", "rpm", "player",
                             "core", "library", "SubgenreTable.kt")


def normalize(value):
    """The same folding as Genres.Normalize: only letters and digits, in lower case."""
    return "".join(c.lower() for c in value if c.isalnum())


def quote(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    with open(SOURCE, encoding="utf8") as f:
        data = json.load(f)

    unknown = data["unknown"]
    shelves = data["shelves"]
    blocked = data["blocked"]

    genres = [s["genre"] for s in shelves]
    if unknown not in genres:
        sys.exit(f"{SOURCE}: 'unknown' ({unknown}) is not one of the shelves.")
    if len(set(genres)) != len(genres):
        sys.exit(f"{SOURCE}: a shelf is listed twice.")

    # A style with the same name as a shelf cannot be told apart from it once both are folded to
    # letters and digits.
    folded_genres = {normalize(g): g for g in genres}
    pairs = []
    for shelf in shelves:
        for name in shelf["subgenres"]:
            if normalize(name) in folded_genres:
                sys.exit(f"{SOURCE}: style {name!r} is spelled like the shelf "
                         f"{folded_genres[normalize(name)]!r}.")
            pairs.append((name, shelf["genre"]))

    # A name under more than one shelf is offered under each shelf, but it is matched to none of them,
    # because a style that belongs to three shelves does not identify any one of them.
    seen = {}
    for name, genre in pairs:
        seen.setdefault(normalize(name), []).append(genre)
    shared = sorted(k for k, v in seen.items() if len(v) > 1)

    # If a blocked word folds to the same key as a real style, that style cannot be matched. This is
    # allowed (half of a shelf label can be spelled exactly like a style), but it is always
    # reported, and the style stays in the picker.
    blocked_keys = {normalize(b) for b in blocked}
    silenced = sorted({name for name, _ in pairs if normalize(name) in blocked_keys})

    # A version number for this table, as a hash and not a number kept by hand, because a number that
    # must be raised by hand is wrong as soon as someone forgets. Everything that can change a mapping
    # goes into it: the pairs, the shared keys and the blocked keys. It is masked to stay a positive
    # int, which is what a database column holds.
    fingerprint = "\n".join(
        [f"{name}|{genre}" for name, genre in pairs]
        + [f"shared|{k}" for k in shared]
        + [f"blocked|{k}" for k in sorted(blocked_keys)])
    version = int(hashlib.sha256(fingerprint.encode("utf8")).hexdigest()[:8], 16) & 0x7FFFFFFF

    lines = []
    w = lines.append
    w("// <auto-generated>")
    w("//     Written by scripts/gen_subgenres.py from scripts/subgenres.json.")
    w("//     Do not edit: every run overwrites this file. Edit the JSON and run the script.")
    w("// </auto-generated>")
    w("")
    w("namespace RPM.Core.Metadata;")
    w("")
    w("public static partial class Subgenres")
    w("{")
    w("    /// <summary>")
    w("    /// What this table is, as a number: a hash of every style, its shelf, and the shared and")
    w("    /// blocked keys.")
    w("    ///")
    w("    /// <para>Stored beside every mapped answer, so that a row mapped by an older list can be")
    w("    /// found and mapped again without asking the catalogue a second time. It changes on its own")
    w("    /// whenever the list changes, because a number somebody has to remember to raise is a number")
    w("    /// that is wrong the first time somebody forgets.</para>")
    w("    /// </summary>")
    w(f"    public const int Version = {version};")
    w("")
    w("    /// <summary>The shelves, in the order they are offered. Generated, so this and the")
    w("    /// styles under it can never disagree about which shelves exist.</summary>")
    w("    public static readonly IReadOnlyList<string> Shelves =")
    w("    [")
    for genre in genres:
        w(f"        {quote(genre)},")
    w("    ];")
    w("")
    w("    /// <summary>Every style and the shelf it hangs off, in offering order. A name appears")
    w("    /// once per shelf it belongs to.</summary>")
    w("    public static readonly IReadOnlyList<Subgenre> All =")
    w("    [")
    for name, genre in pairs:
        w(f"        new({quote(name)}, {quote(genre)}),")
    w("    ];")
    w("")
    w("    /// <summary>Folded names that belong to more than one shelf, and so are matched to")
    w("    /// none. Offered under each of their shelves all the same.</summary>")
    w("    private static readonly string[] SharedKeys =")
    w("    [")
    for key in shared:
        w(f"        {quote(key)},")
    w("    ];")
    w("")
    w("    /// <summary>Words split out of a tag that are never a style: shelf labels cut in half,")
    w("    /// bare modifiers, and facts about a recording. Folded. Used only by the style lookup,")
    w("    /// because several of these are good shelf words.</summary>")
    w("    private static readonly string[] BlockedKeys =")
    w("    [")
    for word in blocked:
        key = normalize(word)
        if key:
            w(f"        {quote(key)}, // {word}")
    w("    ];")
    w("}")
    w("")

    with open(TARGET, "w", encoding="utf8") as f:
        f.write("\n".join(lines))

    write_swift(genres, pairs, shared, blocked, version)
    write_kotlin(genres, pairs, shared, blocked, version)

    print(f"{os.path.relpath(TARGET, ROOT)}: {len(genres)} shelves, {len(pairs)} styles, "
          f"{len(shared)} shared, {len(blocked)} blocked, version {version}")
    for name in silenced:
        print(f"  offered but never matched, a blocked word is spelled the same: {name}")


def write_swift(genres, pairs, shared, blocked, version):
    """The same table for the iPhone app, read by Genres.swift in RPMLibrary."""
    lines = []
    w = lines.append
    w("// <auto-generated>")
    w("//     Written by scripts/gen_subgenres.py from scripts/subgenres.json.")
    w("//     Do not edit: every run overwrites this file. Edit the JSON and run the script.")
    w("// </auto-generated>")
    w("")
    w("/// The shelves and styles, generated from the same JSON as the desktop's")
    w("/// `Subgenres.Data.cs`. See `Genres`, which does the looking up.")
    w("enum SubgenreTable {")
    w(f"    static let version = {version}")
    w("")
    w("    /// The shelves, in the order they are offered.")
    w("    static let shelves: [String] = [")
    for genre in genres:
        w(f"        {quote(genre)},")
    w("    ]")
    w("")
    w("    /// Every style and the shelf it hangs off, in offering order.")
    w("    static let styles: [(name: String, genre: String)] = [")
    for name, genre in pairs:
        w(f"        ({quote(name)}, {quote(genre)}),")
    w("    ]")
    w("")
    w("    /// Folded names that belong to more than one shelf, and so are matched to none.")
    w("    static let sharedKeys: Set<String> = [")
    for key in shared:
        w(f"        {quote(key)},")
    w("    ]")
    w("")
    w("    /// Words split out of a tag that are never a style. Folded. Used only by the style")
    w("    /// lookup.")
    w("    static let blockedKeys: Set<String> = [")
    for word in sorted({normalize(b) for b in blocked if normalize(b)}):
        w(f"        {quote(word)},")
    w("    ]")
    w("}")
    w("")

    with open(SWIFT_TARGET, "w", encoding="utf8") as f:
        f.write("\n".join(lines))
    print(f"{os.path.relpath(SWIFT_TARGET, ROOT)}: written")


def kotlin_quote(value):
    """A Kotlin string literal. `$` starts a template in Kotlin, so it is escaped too."""
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def write_kotlin(genres, pairs, shared, blocked, version):
    """The same table for the Android TV app, read by Genres.kt."""
    lines = []
    w = lines.append
    w("// <auto-generated>")
    w("//     Written by scripts/gen_subgenres.py from scripts/subgenres.json.")
    w("//     Do not edit: every run overwrites this file. Edit the JSON and run the script.")
    w("// </auto-generated>")
    w("")
    w("package com.rpm.player.core.library")
    w("")
    w("/** The shelves and styles, generated from the same JSON as the desktop's `Subgenres.Data.cs`")
    w(" * and the phone's `Subgenres.Data.swift`. See [Genres], which does the looking up. */")
    w("internal object SubgenreTable {")
    w(f"    const val VERSION = {version}")
    w("")
    w("    /** The shelves, in the order they are offered. */")
    w("    val shelves: List<String> = listOf(")
    for genre in genres:
        w(f"        {kotlin_quote(genre)},")
    w("    )")
    w("")
    w("    /** Every style and the shelf it hangs off, in offering order: (name, shelf). */")
    w("    val styles: List<Pair<String, String>> = listOf(")
    for name, genre in pairs:
        w(f"        {kotlin_quote(name)} to {kotlin_quote(genre)},")
    w("    )")
    w("")
    w("    /** Folded names that belong to more than one shelf, and so are matched to none. */")
    w("    val sharedKeys: Set<String> = setOf(")
    for key in shared:
        w(f"        {kotlin_quote(key)},")
    w("    )")
    w("")
    w("    /** Words split out of a tag that are never a style. Folded. Used only by the style")
    w("     * lookup. */")
    w("    val blockedKeys: Set<String> = setOf(")
    for word in sorted({normalize(b) for b in blocked if normalize(b)}):
        w(f"        {kotlin_quote(word)},")
    w("    )")
    w("}")
    w("")

    with open(KOTLIN_TARGET, "w", encoding="utf8") as f:
        f.write("\n".join(lines))
    print(f"{os.path.relpath(KOTLIN_TARGET, ROOT)}: written")


if __name__ == "__main__":
    main()
