#!/usr/bin/env python3
"""Writes the palette of the Swift app from the desktop palette.

RPM.Desktop/Assets/RpmPalette.xaml is the single source of the app's ten accents,
in the same way that scripts/strings.json is the single source of its text. Each
of these colours is a real drawer tint: the album wall's own calculation run over a
real cover, chosen to give a bright spread across the hues. A second set of colours
typed into Swift would differ from the first as soon as the first is changed.

Run it after editing the XAML:

    python3 scripts/gen_palette_swift.py

Never edit the file it writes by hand. A colour removed from the XAML is also removed from
the Swift: the wall then has one accent fewer, and does not draw a colour that the desktop
does not have.
"""

import os
import pathlib
import workspace
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = workspace.at("RPM.Desktop/Assets/RpmPalette.xaml")
TARGET = workspace.at("RPM.iOS/Modules/RPMDesign/Sources/RPMDesign/Palette.generated.swift")

# The names are listed here, not collected from the file, in the order of the asset: warm, green,
# cool, then the magentas and reds. A colour that is renamed in the XAML is reported as missing
# (see the warning in main), so the palette does not become shorter without notice.
NAMES = [
    "Vermilion", "Rust", "Gold", "Lime", "Forest",
    "Azure", "Indigo", "Magenta", "Crimson", "Red",
]


def argb(text):
    """#FFRRGGBB -> (r, g, b). The alpha is always FF here and is dropped."""
    hexed = text.strip().lstrip("#")
    if len(hexed) == 8:
        hexed = hexed[2:]
    return tuple(int(hexed[i:i + 2], 16) for i in (0, 2, 4))


def main():
    if not SOURCE.exists():
        sys.exit(f"no palette at {SOURCE}")

    xaml = SOURCE.read_text()
    colours = dict(re.findall(r'<Color x:Key="Rpm(\w+)Color">([^<]+)</Color>', xaml))

    # Each gradient has three stops under its own key, in the order of the document.
    gradients = {}
    for name, body in re.findall(
        r'<LinearGradientBrush x:Key="Rpm(\w+)Gradient".*?</LinearGradientBrush>',
        xaml, re.S,
    ) and re.findall(
        r'<LinearGradientBrush x:Key="Rpm(\w+)Gradient".*?>(.*?)</LinearGradientBrush>',
        xaml, re.S,
    ):
        gradients[name] = re.findall(r'Color="([^"]+)"', body)

    missing = [n for n in NAMES if n not in colours]
    if missing:
        print(f"warning: not in the XAML, dropped from the Swift: {', '.join(missing)}")

    lines = [
        "// Generated by scripts/gen_palette_swift.py from",
        "// RPM.Desktop/Assets/RpmPalette.xaml. Do not edit by hand.",
        "//",
        "// The XAML is the only source of the app's accents. The desktop and iOS apps read",
        "// the same ten colours, so a change to the XAML reaches both.",
        "",
        "extension RPMPalette {",
        "    /// The accents, in the order the asset lists them.",
        "    public static let accents: [Accent] = [",
    ]

    for name in NAMES:
        if name not in colours:
            continue
        r, g, b = argb(colours[name])
        stops = [argb(s) for s in gradients.get(name, [])]
        stop_text = ", ".join(f"RGB({sr}, {sg}, {sb})" for sr, sg, sb in stops)
        lines.append(
            f'        Accent(name: "{name}", base: RGB({r}, {g}, {b}), '
            f"gradient: [{stop_text}]),"
        )

    lines += ["    ]", "}", ""]

    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text("\n".join(lines))
    print(f"{len([n for n in NAMES if n in colours])} accents -> {os.path.relpath(TARGET, ROOT)}")


if __name__ == "__main__":
    main()
