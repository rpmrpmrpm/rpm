#!/usr/bin/env python3
"""Writes the Android TV app's playlist photographs and their table from scripts/playlist-photos.json.

The TV shows the same photograph behind a generated list's frame as the desktop and the phone do, so
it ships the same files. They are copied byte for byte from RPM.Desktop/Assets/PlaylistPhotos, which
gen_playlist_photos.py cuts to a 640 pixel square. The files are copied and not cut again, because
encoding a JPEG a second time loses detail. The TV decodes each file at the size it draws it.

Output:
    RPM.Android/core/src/main/assets/playlist-photos/<file>.jpg
    RPM.Android/core/src/main/java/com/rpm/player/core/library/PlaylistPhotoFiles.kt

Both are rewritten completely. A list that is removed from the JSON has its file removed here too.
Neither output is edited by hand.

gen_playlist_photos.py runs this at the end, so after editing the JSON, running that one script
updates every app. Run this script on its own when only the TV side needs to be written again:

    python scripts/gen_playlist_photos_tv.py
"""

import io
import json
import workspace
import os
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = workspace.path("scripts", "playlist-photos.json")
DESKTOP = workspace.path("RPM.Desktop", "Assets", "PlaylistPhotos")
APP = workspace.path("RPM.Android", "core", "src", "main")
TARGET = os.path.join(APP, "assets", "playlist-photos")
TABLE = os.path.join(APP, "java", "com", "rpm", "player", "core", "library", "PlaylistPhotoFiles.kt")


def kotlin_string(text):
    """Returns a Kotlin string literal, quotes included."""
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def table(book):
    lines = [
        "// Generated by scripts/gen_playlist_photos_tv.py from scripts/playlist-photos.json.",
        "// Do not edit: this file is overwritten on every run.",
        "",
        "package com.rpm.player.core.library",
        "",
        "import com.rpm.player.core.library.PlaylistPhotos.Cut",
        "",
        "/** Which file under assets/playlist-photos each generated list wears. A list that is not here has",
        " * no photograph. */",
        "internal object PlaylistPhotoFiles {",
        "    /** The square every file is cut to, in pixels. */",
        f"    const val EDGE = {book['edge']}",
        "",
        "    val BY_CUT: Map<Cut, String> = mapOf(",
    ]

    for photo in book["photos"]:
        genre = kotlin_string(photo["genre"]) if photo["genre"] else "null"
        lines.append(
            f"        Cut({kotlin_string(photo['kind'])}, {genre}, {photo['decade']}) to "
            f"{kotlin_string(photo['file'])},")

    lines += ["    )", "}", ""]
    return "\n".join(lines)


def main():
    with io.open(SOURCE, encoding="utf-8") as f:
        book = json.load(f)

    photos = book["photos"]

    # A repeated key would make the later entry in the map literal silently replace the earlier one.
    keys = {}
    for photo in photos:
        key = (photo["kind"], photo["genre"], photo["decade"])
        if key in keys:
            sys.exit(f"two entries for {key}: {keys[key]} and {photo['file']}")
        keys[key] = photo["file"]

    os.makedirs(TARGET, exist_ok=True)

    for photo in photos:
        source = os.path.join(DESKTOP, photo["file"])
        if not os.path.exists(source):
            sys.exit(f"{photo['file']} is not in {os.path.relpath(DESKTOP, ROOT)}. "
                     "Run scripts/gen_playlist_photos.py first.")
        shutil.copyfile(source, os.path.join(TARGET, photo["file"]))

    wanted = {p["file"] for p in photos}
    for stale in sorted(set(os.listdir(TARGET)) - wanted):
        os.remove(os.path.join(TARGET, stale))
        print(f"  removed {stale}")

    with io.open(TABLE, "w", encoding="utf-8", newline="\n") as f:
        f.write(table(book))

    total = sum(os.path.getsize(os.path.join(TARGET, p["file"])) for p in photos)
    print(f"{os.path.relpath(TARGET, ROOT)}: {len(photos)} photographs, {total // 1024} KB")
    print(f"{os.path.relpath(TABLE, ROOT)} written")


if __name__ == "__main__":
    main()
