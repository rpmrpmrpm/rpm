#!/usr/bin/env python3
"""Writes RPM.Core/Lyrics/LyricLexicon.Data.cs from scripts/vader_lexicon.txt.

The source is VADER's lexicon, included unmodified so its origin can be checked. VADER is
MIT licensed (C.J. Hutto, https://github.com/cjhutto/vaderSentiment), and the notice is copied
into the generated file, as the licence requires.

Two of the four columns are kept. The source columns are the word, the mean rating, the standard
deviation, and the ten raw human ratings. The app needs the word and the mean only: the spread and
the raw ratings are only useful to calculate the mean again.

Only plain lowercase words are kept. The rest of the table is emoticons and punctuation faces
(":)", "%-)", "$:"), which a lyric sheet does not contain and which the tokenizer on the C# side
never produces.

The generated file is overwritten on every run. Do not edit it by hand.

Run it after replacing the lexicon:

    python scripts/gen_lyric_lexicon.py
"""

import os
import workspace
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = workspace.path("scripts", "vader_lexicon.txt")
TARGET = workspace.path("RPM.Core", "Lyrics", "LyricLexicon.Data.cs")

# A word as the C# tokenizer produces it: letters, with an apostrophe allowed inside.
WORD = re.compile(r"[a-z][a-z']*[a-z]|[a-z]")

# How many pairs go on one line of the generated table. It is wide enough to keep the file short
# and narrow enough to read a diff.
PER_LINE = 6


def main():
    if not os.path.exists(SOURCE):
        sys.exit(f"missing {SOURCE}: see the note at the top of this script")

    # A dict, not a list: the source lists eight words twice ("ok", "lol", "sob" and five more) with
    # different ratings, and the later entry wins. VADER's own loader does the same, so both entries
    # never reach the table.
    kept = {}
    dropped = 0
    repeated = 0
    with open(SOURCE, encoding="utf8") as f:
        for line in f:
            parts = line.rstrip("\n").split("\t")
            if len(parts) < 2:
                continue
            word, mean = parts[0], parts[1]
            if not WORD.fullmatch(word):
                dropped += 1
                continue
            if word in kept:
                repeated += 1
            kept[word] = float(mean)

    entries = sorted(kept.items())

    body = []
    for i in range(0, len(entries), PER_LINE):
        row = " ".join(f"{w} {v:g}" for w, v in entries[i:i + PER_LINE])
        body.append("        " + row)

    with open(TARGET, "w", encoding="utf8", newline="\n") as f:
        f.write(HEADER.format(kept=len(entries), dropped=dropped))
        f.write("\n".join(body))
        f.write(FOOTER)

    print(f"{TARGET}: {len(entries)} words kept, {dropped} non-word entries dropped, "
          f"{repeated} repeats resolved to the later rating")


