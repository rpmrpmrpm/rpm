#!/usr/bin/env python3
"""Writes the iPhone's playlist photographs and their table from scripts/playlist-photos.json.

The phone shows the same photograph behind a generated list's frame as the desktop does, so it ships
the same files. They are copied byte for byte from RPM.Desktop/Assets/PlaylistPhotos, which
gen_playlist_photos.py cuts to a 640 pixel square. The files are copied and not cut again: the
square is already the size at which a cover is composed on both apps, and encoding a JPEG a second
time loses detail for no gain.

Output:
    RPM.iOS/Modules/RPMArt/Sources/RPMArt/PlaylistPhotos/<file>.jpg
    RPM.iOS/Modules/RPMArt/Sources/RPMArt/PlaylistPhotosData.swift

Both are rewritten completely. A list that is removed from the JSON has its file removed here too.
Neither output is edited by hand.

gen_playlist_photos.py runs this at the end, so after editing the JSON, running that one script
updates both apps. Run this script on its own when only the phone side needs to be written again:

    python3 scripts/gen_playlist_photos_phone.py
"""

import io
import json
import workspace
import os
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = workspace.path("scripts", "playlist-photos.json")
DESKTOP = workspace.path("RPM.Desktop", "Assets", "PlaylistPhotos")
MODULE = workspace.path("RPM.iOS", "Modules", "RPMArt", "Sources", "RPMArt")
TARGET = os.path.join(MODULE, "PlaylistPhotos")
TABLE = os.path.join(MODULE, "PlaylistPhotosData.swift")


def swift_string(text):
    """Returns a Swift string literal, quotes included."""
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def table(book):
    lines = [
        "// Generated by scripts/gen_playlist_photos_phone.py from scripts/playlist-photos.json.",
        "// Do not edit: this file is overwritten on every run.",
        "",
        "import RPMLibrary",
        "",
        "extension PlaylistPhotos {",
        "    /// The square every file in `PlaylistPhotos/` is cut to, in pixels.",
        f"    static let shippedEdge = {book['edge']}",
        "",
        "    /// Which file each generated list wears, keyed on the three fields the computer keys the",
        "    /// list on. A list that is not here has no photograph.",
        "    static let files: [GeneratedCut: String] = [",
    ]

    for photo in book["photos"]:
        genre = swift_string(photo["genre"]) if photo["genre"] else "nil"
        lines.append(
            f"        GeneratedCut(kind: {swift_string(photo['kind'])}, genre: {genre}, "
            f"decade: {photo['decade']}): {swift_string(photo['file'])},")

    lines += ["    ]", "}", ""]
    return "\n".join(lines)


def main():
    with io.open(SOURCE, encoding="utf-8") as f:
        book = json.load(f)

    photos = book["photos"]

    # A repeated key would be a duplicate key in a Swift dictionary literal. That compiles, but the
    # app traps the first time the table is read.
    keys = {}
    for photo in photos:
        key = (photo["kind"], photo["genre"], photo["decade"])
        if key in keys:
            sys.exit(f"two entries for {key}: {keys[key]} and {photo['file']}")
        keys[key] = photo["file"]

    os.makedirs(TARGET, exist_ok=True)

    for photo in photos:
        source = os.path.join(DESKTOP, photo["file"])
        if not os.path.exists(source):
            sys.exit(f"{photo['file']} is not in {os.path.relpath(DESKTOP, ROOT)}. "
                     "Run scripts/gen_playlist_photos.py first.")
        shutil.copyfile(source, os.path.join(TARGET, photo["file"]))

    wanted = {p["file"] for p in photos}
    for stale in sorted(set(os.listdir(TARGET)) - wanted):
        os.remove(os.path.join(TARGET, stale))
        print(f"  removed {stale}")

    with io.open(TABLE, "w", encoding="utf-8", newline="\n") as f:
        f.write(table(book))

    total = sum(os.path.getsize(os.path.join(TARGET, p["file"])) for p in photos)
    print(f"{os.path.relpath(TARGET, ROOT)}: {len(photos)} photographs, {total // 1024} KB")
    print(f"{os.path.relpath(TABLE, ROOT)} written")


if __name__ == "__main__":
    main()
