#!/usr/bin/env python3
"""Writes the folder photographs and their tables from scripts/folder-photos.json.

Each of the app's own playlist folders (the moods, the decades, one per mood) shows a photograph of
its own behind the folder frame. This script fetches each one (from the cache when it is there),
cuts it to a centred square of `edge` pixels, and writes it into the desktop app and both phone apps
with a table of which folder wears which file.

Output:
    RPM.Desktop/Assets/FolderPhotos/<file>.jpg
    RPM.Desktop/Presentation/Common/FolderPhotos.Data.cs
    RPM.iOS/Modules/RPMArt/Sources/RPMArt/FolderPhotos/<file>.jpg
    RPM.iOS/Modules/RPMArt/Sources/RPMArt/FolderPhotosData.swift
    RPM.Android/core/src/main/assets/folder-photos/<file>.jpg
    RPM.Android/core/src/main/java/com/rpm/player/core/library/FolderPhotoFiles.kt

All six are rewritten completely, and a folder removed from the JSON has its file removed too.
None of them is edited by hand. The sources are cached under scripts/.photocache, which the genre
and playlist photograph scripts share. A pinned `source` is fetched without a key.

This script does not import gen_playlist_photos.py: that script runs on import and rewrites every
playlist photograph.

    python scripts/gen_folder_photos.py
"""

import io
import json
import os
import sys
import urllib.request

import workspace

try:
    from PIL import Image, ImageOps
except ImportError:
    sys.exit("This needs Pillow: python -m pip install pillow")

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = workspace.path("scripts", "folder-photos.json")
CACHE = workspace.path("scripts", ".photocache")

DESKTOP = workspace.path("RPM.Desktop")
DESKTOP_FILES = os.path.join(DESKTOP, "Assets", "FolderPhotos")
DESKTOP_TABLE = os.path.join(DESKTOP, "Presentation", "Common", "FolderPhotos.Data.cs")

IOS_MODULE = workspace.path("RPM.iOS", "Modules", "RPMArt", "Sources", "RPMArt")
IOS_FILES = os.path.join(IOS_MODULE, "FolderPhotos")
IOS_TABLE = os.path.join(IOS_MODULE, "FolderPhotosData.swift")

ANDROID_CORE = workspace.path("RPM.Android", "core", "src", "main")
ANDROID_FILES = os.path.join(ANDROID_CORE, "assets", "folder-photos")
ANDROID_TABLE = os.path.join(ANDROID_CORE, "java", "com", "rpm", "player", "core", "library",
                             "FolderPhotoFiles.kt")

# Pexels refuses Python's default User-Agent with a 403.
AGENT = "rpm-playlist-photos/1.0"


def fetch(photo):
    """The file of one photograph, from the cache or from its pinned source."""
    path = os.path.join(CACHE, f"{photo['id']}.jpg")
    if os.path.exists(path) and os.path.getsize(path) > 0:
        return path
    os.makedirs(CACHE, exist_ok=True)
    request = urllib.request.Request(photo["source"], headers={"User-Agent": AGENT})
    with urllib.request.urlopen(request, timeout=120) as reply:
        blob = reply.read()
    with open(path, "wb") as f:
        f.write(blob)
    return path


def square(path, edge):
    """The middle square of a photograph at `edge` pixels, after its EXIF turn."""
    with Image.open(path) as opened:
        picture = ImageOps.exif_transpose(opened).convert("RGB")
        return ImageOps.fit(picture, (edge, edge), method=Image.LANCZOS, centering=(0.5, 0.5))


def quoted(text, dollar=False):
    """A Swift or Kotlin string literal, quotes included."""
    text = text.replace("\\", "\\\\").replace('"', '\\"')
    if dollar:
        text = text.replace("$", "\\$")
    return '"' + text + '"'


def swift_table(book):
    lines = [
        "// Generated by scripts/gen_folder_photos.py from scripts/folder-photos.json.",
        "// Do not edit: this file is overwritten on every run.",
        "",
        "extension PlaylistPhotos {",
        "    /// Which file in `FolderPhotos/` each of the app's own folders wears, by the folder's key:",
        "    /// \"moods\", \"decades\", or \"mood:\" and the mood's kind.",
        "    static let folderFiles: [String: String] = [",
    ]
    for photo in book["photos"]:
        lines.append(f"        {quoted(photo['folder'])}: {quoted(photo['file'])},")
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


def csharp_table(book):
    lines = [
        "// <auto-generated>",
        "//     Written by scripts/gen_folder_photos.py from scripts/folder-photos.json. Do not edit:",
        "//     this file is overwritten whole on every run, and a folder taken out of the JSON",
        "//     disappears from here and its picture is deleted from Assets/FolderPhotos.",
        "// </auto-generated>",
        "",
        "// Written inside an explicit annotations context: the compiler will not take a `?` in",
        "// auto-generated code on the project's setting alone (CS8669).",
        "#nullable enable",
        "",
        "namespace RPM.Desktop.Presentation.Common;",
        "",
        "internal static partial class FolderPhotos",
        "{",
        "    /// <summary>Which file in <c>Assets/FolderPhotos</c> each of the app's own folders wears, by",
        "    /// the folder's key: \"moods\", \"decades\", or \"mood:\" and the mood's kind.</summary>",
        "    internal static readonly IReadOnlyDictionary<string, string> Files =",
        "        new Dictionary<string, string>(StringComparer.Ordinal)",
        "        {",
    ]
    for photo in book["photos"]:
        lines.append(f"            [{quoted(photo['folder'])}] = {quoted(photo['file'])},")
    lines += ["        };", "}", ""]
    return "\n".join(lines)


def kotlin_table(book):
    lines = [
        "// Generated by scripts/gen_folder_photos.py from scripts/folder-photos.json.",
        "// Do not edit: this file is overwritten on every run.",
        "",
        "package com.rpm.player.core.library",
        "",
        "/**",
        " * Which file in the assets' `folder-photos/` each of the app's own folders wears, by the folder's key:",
        ' * "moods", "decades", or "mood:" and the mood\'s kind.',
        " */",
        "internal object FolderPhotoFiles {",
        f"    const val SHIPPED_EDGE = {book['edge']}",
        "",
        "    val files: Map<String, String> = mapOf(",
    ]
    for photo in book["photos"]:
        lines.append(f"        {quoted(photo['folder'], True)} to {quoted(photo['file'], True)},")
    lines += ["    )", "}", ""]
    return "\n".join(lines)


def write_files(folder, cuts, quality):
    os.makedirs(folder, exist_ok=True)
    for name, cut in cuts.items():
        cut.save(os.path.join(folder, name), "JPEG", quality=quality, optimize=True, progressive=True)
    for stale in sorted(set(os.listdir(folder)) - set(cuts)):
        os.remove(os.path.join(folder, stale))
        print(f"  removed {stale}")


def main():
    with io.open(SOURCE, encoding="utf-8") as f:
        book = json.load(f)

    seen_folders, seen_files = set(), set()
    for photo in book["photos"]:
        if photo["folder"] in seen_folders or photo["file"] in seen_files:
            sys.exit(f"{photo['folder']} / {photo['file']} is in the table twice")
        seen_folders.add(photo["folder"])
        seen_files.add(photo["file"])

    # Each folder photograph must differ from every list's: the folders hold those lists.
    with io.open(workspace.path("scripts", "playlist-photos.json"), encoding="utf-8") as f:
        list_ids = {p["id"] for p in json.load(f)["photos"]}
    for photo in book["photos"]:
        if photo["id"] in list_ids:
            sys.exit(f"{photo['folder']}: photograph {photo['id']} is a list's photograph too")

    cuts = {p["file"]: square(fetch(p), book["edge"]) for p in book["photos"]}
    write_files(DESKTOP_FILES, cuts, book["quality"])
    write_files(IOS_FILES, cuts, book["quality"])
    write_files(ANDROID_FILES, cuts, book["quality"])

    with io.open(DESKTOP_TABLE, "w", encoding="utf-8", newline="\n") as f:
        f.write(csharp_table(book))
    with io.open(IOS_TABLE, "w", encoding="utf-8", newline="\n") as f:
        f.write(swift_table(book))
    with io.open(ANDROID_TABLE, "w", encoding="utf-8", newline="\n") as f:
        f.write(kotlin_table(book))

    total = sum(os.path.getsize(os.path.join(IOS_FILES, name)) for name in cuts)
    print(f"{len(cuts)} folder photographs, {total // 1024} KB, written to the desktop and both phones")


if __name__ == "__main__":
    main()
