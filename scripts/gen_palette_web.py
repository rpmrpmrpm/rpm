#!/usr/bin/env python3
"""Writes the palette of the web app from the desktop palette: CSS variables for the styles, and a
TypeScript table for code that needs the numbers (the frame on a generated list's cover).

RPM.Desktop/Assets/RpmPalette.xaml is the single source of the app's ten accents, as
gen_palette_swift.py explains. Run it after editing the XAML:

    python3 scripts/gen_palette_web.py

Never edit the file it writes by hand.
"""

import pathlib
import re
import sys

import workspace

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = workspace.at("RPM.Desktop/Assets/RpmPalette.xaml")
TARGET = pathlib.Path(workspace.PARENT) / "rpm-web" / "src" / "design" / "palette.generated.css"
TABLE = TARGET.with_name("palette.generated.ts")

NAMES = [
    "Vermilion", "Rust", "Gold", "Lime", "Forest",
    "Azure", "Indigo", "Magenta", "Crimson", "Red",
]


def css(text):
    """#FFRRGGBB -> #RRGGBB. The alpha is always FF here."""
    hexed = text.strip().lstrip("#")
    return "#" + (hexed[2:] if len(hexed) == 8 else hexed).lower()


def rgb(text):
    """#FFRRGGBB -> [r, g, b]."""
    hexed = css(text).lstrip("#")
    return [int(hexed[i:i + 2], 16) for i in (0, 2, 4)]


def table(colours, gradients):
    """The same accents as numbers, in the order of NAMES, which is the order of the ring."""
    lines = [
        "// Generated by scripts/gen_palette_web.py from RPM.Desktop/Assets/RpmPalette.xaml.",
        "// Do not edit by hand.",
        "",
        "export type Rgb = readonly [number, number, number];",
        "",
        "export interface Accent {",
        "  name: string;",
        "  base: Rgb;",
        "  // Top, middle, foot.",
        "  gradient: readonly Rgb[];",
        "}",
        "",
        "export const accents: readonly Accent[] = [",
    ]
    for name in NAMES:
        if name not in colours:
            continue
        stops = ", ".join(str(rgb(c)) for _, c in gradients.get(name, []))
        lines.append(f"  {{ name: '{name}', base: {rgb(colours[name])}, gradient: [{stops}] }},")
    lines += ["];", ""]
    return "\n".join(lines)


def main():
    if not SOURCE.exists():
        sys.exit(f"no palette at {SOURCE}")
    if not TARGET.parent.parent.parent.is_dir():
        sys.exit(f"no rpm-web at {TARGET.parent.parent.parent}")

    xaml = SOURCE.read_text()
    colours = dict(re.findall(r'<Color x:Key="Rpm(\w+)Color">([^<]+)</Color>', xaml))
    gradients = {
        name: re.findall(r'Offset="([^"]+)"\s+Color="([^"]+)"', body)
        for name, body in re.findall(
            r'<LinearGradientBrush x:Key="Rpm(\w+)Gradient".*?>(.*?)</LinearGradientBrush>', xaml, re.S
        )
    }

    missing = [n for n in NAMES if n not in colours]
    if missing:
        print(f"warning: not in the XAML, dropped from the CSS: {', '.join(missing)}")

    lines = [
        "/* Generated by scripts/gen_palette_web.py from RPM.Desktop/Assets/RpmPalette.xaml.",
        "   Do not edit by hand. */",
        ":root {",
    ]
    for name in NAMES:
        if name not in colours:
            continue
        key = name.lower()
        lines.append(f"  --rpm-{key}: {css(colours[name])};")
        stops = ", ".join(f"{css(c)} {float(o) * 100:g}%" for o, c in gradients.get(name, []))
        lines.append(f"  --rpm-{key}-gradient: linear-gradient(180deg, {stops});")
    lines += ["}", ""]

    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text("\n".join(lines))
    TABLE.write_text(table(colours, gradients))
    print(f"{len([n for n in NAMES if n in colours])} accents -> {TARGET}")


if __name__ == "__main__":
    main()
